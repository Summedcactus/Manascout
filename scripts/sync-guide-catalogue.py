"""Synchronise the static guide catalogue. Use --check to verify committed output."""
import argparse
from datetime import date
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://manascout.co.uk"
CATEGORIES = {"original", "premium", "artwork"}
SLUG = r"[a-z0-9]+(?:-[a-z0-9]+)*"


def load_guides():
    guides = json.loads((ROOT / "data/guides.json").read_text())
    slugs = [guide["slug"] for guide in guides]
    if not slugs or any(not re.fullmatch(SLUG, slug) for slug in slugs) or len(slugs) != len(set(slugs)):
        raise ValueError("Manifest guide slugs must be unique canonical slugs")
    for guide in guides:
        tags = guide["categories"]
        if not guide["name"].strip() or not tags or len(tags) != len(set(tags)) or set(tags) - CATEGORIES:
            raise ValueError(f"Missing name or invalid taxonomy for {guide['slug']}")
        if date.fromisoformat(guide["lastmod"]).isoformat() != guide["lastmod"]:
            raise ValueError(f"Use a YYYY-MM-DD lastmod for {guide['slug']}")
    pages = {path.parent.name for path in (ROOT / "card").glob("*/index.html")}
    if set(slugs) != pages:
        raise ValueError(f"Manifest/page mismatch: {sorted(pages ^ set(slugs))}")
    return guides


def guide_path(guide):
    return f"/card/{guide['slug']}/"


def replace_once(pattern, replacement, source):
    result, changes = re.subn(pattern, replacement, source)
    if changes != 1:
        raise ValueError(f"Expected one generated field for {pattern}, found {changes}")
    return result


def archive_html(source, guides):
    by_slug = {guide["slug"]: guide for guide in guides}
    count = len(guides)
    found = []

    def tag_entry(match):
        slug = match[2]
        if slug not in by_slug:
            raise ValueError(f"Archive entry {slug} needs a manifest record")
        found.append(slug)
        return f'{match[1]} data-guide-tags="{" ".join(by_slug[slug]["categories"])}"'

    source = re.sub(r'(<a class="hub-guide" href="/card/(' + SLUG + r')/")(?: data-guide-tags="[^"]*")?',
                    tag_entry, source)
    if sorted(found) != sorted(by_slug):
        raise ValueError("Each manifest guide needs exactly one authored card in the archive")

    def schema(match):
        graph = json.loads(match[2])
        collection = next(node for node in graph["@graph"] if node["@type"] == "CollectionPage")
        collection["description"] = f"A directory of {count} Magic: The Gathering card printing guides."
        items = next(node for node in graph["@graph"] if node["@type"] == "ItemList")
        items["numberOfItems"] = count
        ordered = sorted(guides, key=lambda guide: re.sub(r"[^a-z0-9 ]", "", guide["name"].lower()))
        items["itemListElement"] = [
            {"@type": "ListItem", "position": index, "name": guide["name"], "url": ORIGIN + guide_path(guide)}
            for index, guide in enumerate(ordered, 1)
        ]
        encoded = json.dumps(graph, ensure_ascii=False, indent=2).replace("<", "\\u003c")
        return match[1] + encoded + match[3]

    source = replace_once(r'(<script type="application/ld\+json">)([\s\S]*?)(</script>)', schema, source)
    for before, after in (
        ("Explore ", " Magic: The Gathering card printing guides."),
        ("Browse ", " guides covering original releases"),
        ("Explore ", " Magic card guides covering"),
        ("Explore ", " Magic: The Gathering card guides."),
        ('id="hub-total">', "</span>"),
        ('aria-live="polite"\n        >\n          ', " guides\n"),
    ):
        source = replace_once(re.escape(before) + r"\d+" + re.escape(after), f"{before}{count}{after}", source)
    return source


def sitemap_xml(source, guides):
    directory = ORIGIN + "/card/"
    expected = {ORIGIN + guide_path(guide): guide["lastmod"] for guide in guides}
    found = set()

    def entry(match):
        url = match[2]
        if url == directory:
            return match[1] + max(match[3], max(expected.values())) + match[4]
        if not url.startswith(directory):
            return match[0]
        if url in found:
            raise ValueError(f"Duplicate guide URL in sitemap: {url}")
        found.add(url)
        return match[1] + expected[url] + match[4] if url in expected else ""

    source = re.sub(r'(^  <url>\s*<loc>([^<]+)</loc>\s*<lastmod>)([^<]+)(</lastmod>\s*</url>\n)',
                    entry, source, flags=re.M)
    missing = "".join(
        f"  <url>\n    <loc>{url}</loc>\n    <lastmod>{expected[url]}</lastmod>\n  </url>\n"
        for url in sorted(expected.keys() - found)
    )
    return replace_once(r"</urlset>", missing + "</urlset>", source)


def registry_js(guides):
    slugs = json.dumps(sorted(guide["slug"] for guide in guides), indent=2)
    return f'''/* Generated by scripts/sync-guide-catalogue.py from data/guides.json. */
((root) => {{
  "use strict";
  const slugs = Object.freeze({slugs});
  const catalogue = Object.freeze({{ slugs }});
  if (typeof module === "object" && module.exports) module.exports = catalogue;
  else root.ManaScoutGuideCatalogue = catalogue;
}})(typeof window === "undefined" ? globalThis : window);
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    guides = load_guides()
    outputs = {
        "assets/js/guide-catalogue.js": registry_js(guides),
        "card/index.html": archive_html((ROOT / "card/index.html").read_text(), guides),
        "sitemap.xml": sitemap_xml((ROOT / "sitemap.xml").read_text(), guides),
        "deck/index.html": replace_once(r"Explore \d+ card guides", f"Explore {len(guides)} card guides",
                                       (ROOT / "deck/index.html").read_text()),
    }
    stale = []
    for file, output in outputs.items():
        path = ROOT / file
        if not path.is_file() or path.read_text() != output:
            stale.append(file)
            if not args.check:
                path.write_text(output)
    if args.check and stale:
        parser.exit(1, "Guide catalogue output is stale. Run scripts/sync-guide-catalogue.py.\n" +
                    "\n".join(stale) + "\n")
    print(f"Guide catalogue {'verified' if args.check else 'synchronised'} ({len(guides)} guides).")


if __name__ == "__main__":
    main()
